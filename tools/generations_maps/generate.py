#!/usr/bin/env python3
"""Build the HGSS-based GBA maps and palette-limited tiles from checked-in sources.

Requires Pillow only when regenerating; normal ROM builds use the generated files.
`--check` compares regenerated bytes without modifying the checkout.
"""
import argparse
import io
import json
import math
import struct
from collections import deque
from pathlib import Path
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[2]
REF = json.loads((Path(__file__).with_name('hgss_reference.json')).read_text())
OUTPUTS = {}

def emit(path, data):
    OUTPUTS[path] = data.encode() if isinstance(data, str) else data

def png(im):
    b = io.BytesIO(); im.save(b, format='PNG'); return b.getvalue()

def palette(path):
    return [tuple(map(int, row.split())) for row in (ROOT/path).read_text().splitlines()[3:19]]

def palfile(colors):
    return 'JASC-PAL\n0100\n16\n' + ''.join('%d %d %d\n' % c for c in colors)

# Dedicated Johto colors. Share the primary tile shapes and animation callback;
# do not alter the Kanto palettes or any Kanto map/tileset data.
primary_palettes = []
for bank in range(7):
    colors = palette(f'data/tilesets/primary/general_frlg/palettes/{bank:02}.pal')
    recolored = []
    for red, green, blue in colors:
        if green > red * 1.08 and green > blue * 1.08:
            red, green, blue = min(255, int(red * 1.10)), int(green * .95), int(blue * .80)
        recolored.append((red, green, blue))
    primary_palettes.append(recolored)
    emit(f'data/tilesets/primary/johto/palettes/{bank:02}.pal', palfile(recolored))

primary_meta = list(struct.iter_unpack('<8H', (ROOT/'data/tilesets/primary/general_frlg/metatiles.bin').read_bytes()))
primary_attrs = struct.unpack('<640I', (ROOT/'data/tilesets/primary/general_frlg/metatile_attributes.bin').read_bytes())
primary_tiles = Image.open(ROOT/'data/tilesets/primary/general_frlg/tiles.png')
secondary_tiles = [bytes(64)]
tile_indices = {bytes(64): 0}
metatiles = []
attributes = []
secondary_palettes = [(0, 0, 0)] * 16
secondary_palettes = [list(secondary_palettes) for _ in range(13)]

def tile_index(tile):
    raw = tile.tobytes()
    if raw not in tile_indices:
        tile_indices[raw] = len(secondary_tiles)
        secondary_tiles.append(raw)
    return 640 + tile_indices[raw]

def add_meta(top, bank, behavior=0, base=1):
    words = list(primary_meta[base][:4])
    for q in range(4):
        tile = top.crop(((q % 2)*8, (q//2)*8, (q % 2)*8+8, (q//2)*8+8))
        words.append(tile_index(tile) | (bank << 12))
    metatiles.append(words)
    # FRLG attribute layout: 32 bits, with the layer mode in bits 29..30.
    attributes.append(behavior)
    return 640 + len(metatiles) - 1

assets = {}
for name, spec in REF['assets'].items():
    rgba = Image.open(ROOT/spec['path']).convert('RGBA')
    # The community sheet was doubled from native 16px to RPG Maker's 32px.
    rgba = rgba.resize((rgba.width//2, rgba.height//2), Image.Resampling.NEAREST)
    for y in range(rgba.height):
        for x in range(rgba.width):
            red, green, blue, alpha = rgba.getpixel((x, y))
            if (red, green, blue) == (255, 245, 104):
                rgba.putpixel((x, y), (0, 0, 0, 0))
            elif (red, green, blue) == (180, 180, 188):
                rgba.putpixel((x, y), (104, 153, 98, alpha))
    size = (math.ceil(rgba.width/16)*16, math.ceil(rgba.height/16)*16)
    padded = Image.new('RGBA', size); padded.paste(rgba, (0, 0))
    rgb = Image.new('RGB', size, (0, 0, 0)); rgb.paste(padded, mask=padded.getchannel('A'))
    # Quantize visible pixels only. Color index zero is reserved for transparency.
    visible = [padded.getpixel((x, y))[:3] for y in range(size[1]) for x in range(size[0]) if padded.getpixel((x, y))[3]]
    samples = Image.new('RGB', (len(visible), 1)); samples.putdata(visible)
    quantized = samples.quantize(colors=15, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    colors = [tuple(quantized.getpalette()[i:i+3]) for i in range(0, 45, 3)]
    secondary_palettes[spec['palette']] = [(0, 0, 0)] + colors
    indexed = Image.new('P', size)
    cache = {}
    for y in range(size[1]):
        for x in range(size[0]):
            color = padded.getpixel((x, y))
            if color[3]:
                rgb = color[:3]
                if rgb not in cache:
                    cache[rgb] = 1 + min(range(15), key=lambda i: sum((rgb[c]-colors[i][c])**2 for c in range(3)))
                indexed.putpixel((x, y), cache[rgb])
    grid = []
    for y in range(size[1]//16):
        row = []
        for x in range(size[0]//16):
            top = indexed.crop((x*16, y*16, x*16+16, y*16+16))
            row.append(add_meta(top, spec['palette']) if top.getbbox() else None)
        grid.append(row)
    # A custom nonanimated doorway avoids using Pallet's door-animation graphics.
    dx, dy = spec['door']
    door_art = indexed.crop((dx*16, dy*16, dx*16+16, dy*16+16))
    d = ImageDraw.Draw(door_art)
    dark = 1 + min(range(15), key=lambda i: sum(colors[i]))
    d.rectangle((3, 2, 12, 15), fill=dark)
    door_id = add_meta(door_art, spec['palette'], behavior=0x60)
    grid[dy][dx] = door_id
    assets[name] = {'grid': grid, 'door': spec['door'], 'width': size[0]//16, 'height': size[1]//16}

# Original small wind-turbine pixel art: an HGSS New Bark landmark, not a
# character sprite or a Pallet decoration. All colors fit one GBA palette.
secondary_palettes[11] = [(0,0,0),(232,239,223),(154,174,168),(95,119,113),(62,83,81),(193,207,187)] + [(0,0,0)]*10
turbine = Image.new('P', (48, 64)); d = ImageDraw.Draw(turbine)
d.polygon([(23,17),(25,17),(27,61),(20,61)], fill=2)
d.line([(24,18),(24,59)],fill=1,width=2)
d.polygon([(24,19),(22,2),(25,0),(27,17)],fill=1)
d.polygon([(24,19),(7,30),(3,28),(21,17)],fill=1)
d.polygon([(24,19),(42,28),(43,32),(25,22)],fill=1)
d.ellipse((20,15,28,23),fill=3);d.ellipse((22,17,26,21),fill=1)
d.rectangle((18,60,28,63),fill=4)
turbine_grid = [[add_meta(turbine.crop((x*16,y*16,x*16+16,y*16+16)),11) for x in range(3)] for y in range(4)]

# Reuse an existing sign's graphics, but bind it to Johto's own sign scripts.
sign_id = 3

def decode(name):
    return [[int(row[x:x+4], 16) for x in range(0,128,4)] for row in REF['terrain'][name]]

class Map:
    def __init__(self, name, terrain):
        self.name = name; self.h = len(terrain); self.w = len(terrain[0]); self.terrain = terrain
        self.blocks = [[0 for _ in row] for row in terrain]
        for y, row in enumerate(terrain):
            for x, attr in enumerate(row):
                behavior = attr & 255
                blocked = bool(attr & 0x8000)
                tile = 1
                if behavior == 6:
                    tile = ((0x1c,0x1d),(0x14,0x15))[y%2][x%2]
                elif behavior == 2:
                    tile = ((0x0a,0x0b),(0x0c,0x0d))[y%2][x%2]
                elif behavior in (0x10,0x15):
                    tile = 0x204; blocked = False
                elif behavior == 0x38:
                    tile = 0x8c
                elif behavior == 0x39:
                    tile = 0x8b
                elif behavior in (0x3b,0x3e):
                    tile = 0x8f
                elif attr == 0x400:
                    # Autotile the soil roads from the HGSS walking-surface mask.
                    def road(xx, yy):
                        return 0 <= yy < self.h and 0 <= xx < self.w and terrain[yy][xx] == 0x400
                    left, right, up, down = road(x-1,y), road(x+1,y), road(x,y-1), road(x,y+1)
                    col = 0 if not left and right else 2 if left and not right else 1
                    row = 0 if not up and down else 2 if up and not down else 1
                    tile = ((0xd0,0xd1,0xd2),(0xd8,0xd9,0xda),(0xe0,0xe1,0xe2))[row][col]
                elif blocked:
                    # Buildings will overwrite these cells; remaining small
                    # obstructions become shrubs rather than invisible walls.
                    tile = 5
                self.blocks[y][x] = tile | (0xc00 if blocked else 0) | (0x1000 if behavior in (0x10,0x15) else 0x3000)
    def set(self,x,y,tile,blocked=False,elevation=3):
        if 0 <= x < self.w and 0 <= y < self.h:
            self.blocks[y][x] = tile | (0xc00 if blocked else 0) | (elevation << 12)
    def stamp(self,asset,door):
        a = assets[asset]; dx,dy = a['door']; ox,oy = door[0]-dx,door[1]-dy
        for y,row in enumerate(a['grid']):
            for x,tile in enumerate(row):
                if tile is not None:
                    self.set(ox+x,oy+y,tile,blocked=(y <= dy and (x,y)!=(dx,dy)))
        self.set(*door,a['grid'][dy][dx])
        # Leave a clear, visible approach to each entrance.
        for x in range(door[0]-1,door[0]+2):self.set(x,door[1]+1,0xd9)
    def sign(self,x,y):self.set(x,y,sign_id,True)
    def save(self):
        emit(f'data/layouts/{self.name}/map.bin',struct.pack('<'+'H'*(self.w*self.h),*(b for row in self.blocks for b in row)))
        emit(f'data/layouts/{self.name}/border.bin',struct.pack('<4H',0x3c1c,0x3c1d,0x3c14,0x3c15))

town = Map('NewBarkTown', decode('new_bark'))
route = Map('JohtoRoute29', [decode('route29_west')[y]+decode('route29_middle')[y]+decode('route29_east')[y] for y in range(32)])
for key, asset in [('lab','lab'),('player_home','house'),('southwest_home','cottage'),('rival_home','house')]:
    town.stamp(asset,REF['town_doors'][key])
# The outside stairs lead to Elm's upstairs study, like the HGSS lab.
stair_image = Image.new('P',(16,16));sd=ImageDraw.Draw(stair_image)
for y in range(0,16,3):sd.rectangle((1,y,14,y+1),fill=2)
stair_id = add_meta(stair_image,11,0x60)
town.set(16,8,stair_id)
town.set(16,9,add_meta(stair_image,11))
town.set(16,10,0xd9)
for x,y in [(4,10),(19,6),(3,27)]:
    for yy,row in enumerate(turbine_grid):
        for xx,tile in enumerate(row):town.set(x-1+xx,y-3+yy,tile,blocked=(yy==3 and xx==1))
# Keep the HGSS west connection at the original road's latitude.
for y in range(12,19):
    for x in range(0,5):town.set(x,y,0xd9)
    for x in range(92,96):route.set(x,y,0xd9)
assets['gate'] = assets['lab']
route.stamp('gate',REF['route_gate'])
# The gate has two entrance tiles in HGSS; keep both usable in this adaptation.
route.set(51,5,assets['gate']['grid'][assets['gate']['door'][1]][assets['gate']['door'][0]])
# Cherrygrove and Route 46 are outside the current milestone. Visible fences,
# not a connection to a Kanto map, close those unfinished boundaries.
for y in range(12,19):route.set(0,y,0xe7,True)
route.sign(3,13)
for x,y in [(10,9),(21,12),(16,23)]:town.sign(x,y)
for x,y in [(86,13),(50,8)]:route.sign(x,y)
town.save();route.save()

if len(secondary_tiles) > 384:
    raise RuntimeError(f'{len(secondary_tiles)} secondary tiles exceed FRLG capacity (384)')
if len(metatiles) > 384:
    raise RuntimeError('Too many secondary metatiles')
# Porymap/game use a 16-tile-wide indexed sheet; gbagfx preserves the indices.
sheet = Image.new('P',(128,math.ceil(len(secondary_tiles)/16)*8))
sheet.putpalette([v for i in range(256) for v in (255-i,)*3])
for i,raw in enumerate(secondary_tiles):
    tile = Image.frombytes('P',(8,8),raw);sheet.paste(tile,(i%16*8,i//16*8))
emit('data/tilesets/secondary/johto/tiles.png',png(sheet))
emit('data/tilesets/secondary/johto/metatiles.bin',b''.join(struct.pack('<8H',*m) for m in metatiles))
emit('data/tilesets/secondary/johto/metatile_attributes.bin',struct.pack('<'+'I'*len(attributes),*attributes))
for i,colors in enumerate(secondary_palettes):emit(f'data/tilesets/secondary/johto/palettes/{i:02}.pal',palfile(colors))

# Expose metadata to the validation tool without executing an emulator.
MAPS = {'NewBarkTown':town,'JohtoRoute29':route}

def render(map_):
    colors = primary_palettes + secondary_palettes[7:]
    def metatile(mid):
        words = primary_meta[mid] if mid < 640 else metatiles[mid-640]
        out = Image.new('RGB',(16,16))
        for layer in range(2):
            for q in range(4):
                word=words[layer*4+q];tid=word&1023
                if tid<640:tile=primary_tiles.crop((tid%16*8,tid//16*8,tid%16*8+8,tid//16*8+8))
                else:tile=Image.frombytes('P',(8,8),secondary_tiles[tid-640])
                if word&1024:tile=tile.transpose(Image.Transpose.FLIP_LEFT_RIGHT)
                if word&2048:tile=tile.transpose(Image.Transpose.FLIP_TOP_BOTTOM)
                for y in range(8):
                    for x in range(8):
                        v=tile.getpixel((x,y))
                        if layer==0 or v:out.putpixel((q%2*8+x,q//2*8+y),colors[word>>12][v])
        return out
    out=Image.new('RGB',(map_.w*16,map_.h*16));cache={}
    for y,row in enumerate(map_.blocks):
        for x,b in enumerate(row):
            mid=b&1023
            if mid not in cache:cache[mid]=metatile(mid)
            out.paste(cache[mid],(x*16,y*16))
    return out

if __name__ == '__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');parser.add_argument('--preview',type=Path)
    args=parser.parse_args();differences=[]
    for path,data in OUTPUTS.items():
        target=ROOT/path
        if args.check:
            if not target.exists() or target.read_bytes()!=data:differences.append(path)
        else:
            target.parent.mkdir(parents=True,exist_ok=True);target.write_bytes(data)
    if differences:raise SystemExit('Generated files differ: '+', '.join(differences))
    if args.preview:
        args.preview.mkdir(parents=True,exist_ok=True)
        for name,map_ in MAPS.items():render(map_).save(args.preview/(name+'.png'))
    print(f'{len(secondary_tiles)}/384 tiles; {len(metatiles)}/384 metatiles; {len(OUTPUTS)} generated files verified' if args.check else f'Generated {len(OUTPUTS)} files: {len(secondary_tiles)}/384 tiles, {len(metatiles)}/384 metatiles')
